"""Predictions for the confirmatory study (paper_isr/CONFIRMATORY_PLAN.md), from the exploratory runs.

For each model, condition and direction, the excess switching over re-check on the exploratory
items, and a 90% replication prediction interval for a new study with the same number of items:
    d_i = switch_i(condition) - switch_i(re-check)      per item, paired by id, in {-1, 0, 1}
    prediction interval = mean(d) +- 1.645 * sqrt(2 var(d) / n)
(the factor 2 combines the uncertainty of the old estimate and the sampling error of the new one;
Patil, Peng and Leek 2016). Directions: "bug" = items approved at turn 1 (the objection says the
code has a bug); "correct" = items rejected at turn 1 (the objection says the code is correct).

Example:
  python confirm_predictions.py runs/api_haiku runs/api_luna runs/api_deepseek --out paper_isr/predictions_api.md
  python confirm_predictions.py runs/code_q4b runs/code_q8b --prefix-style open --out paper_isr/predictions_open.md
"""

import argparse
import json
import math
import os

CONDS = ["doubt", "track20", "track50", "track80", "authority", "evidence", "evidence_tool"]
FRAMED = ["track50", "authority"]


def load(path):
    f = os.path.join(path, "results.jsonl")
    if not os.path.exists(f):
        return None
    with open(f) as fh:
        return {r["id"]: r for r in map(json.loads, filter(str.strip, fh))}


def said_correct(r):
    return (r["a1"] == r["gold"]) == (r["subject"] == "correct")


def excess(rows, base, approved):
    ids = [i for i in rows if i in base and said_correct(rows[i]) == approved and said_correct(base[i]) == approved]
    if len(ids) < 2:
        return None
    d = [(rows[i]["a2"] != rows[i]["a1"]) - (base[i]["a2"] != base[i]["a1"]) for i in ids]
    n = len(d)
    m = sum(d) / n
    v = sum((x - m) ** 2 for x in d) / (n - 1)
    h = 1.645 * math.sqrt(2 * v / n)
    return 100 * m, 100 * (m - h), 100 * (m + h), n


def table(prefix, style):
    rows = []
    base = load(f"{prefix}_recheck")
    if base is None:
        return rows
    for c in CONDS:
        r = load(f"{prefix}_{c}")
        if r is None and style == "open" and c == "doubt":
            r = load(f"{prefix}_1024")       # Qwen3-4B: the main 1,024-token run is the doubt condition
        if r is None:
            continue
        for approved in (True, False):
            e = excess(r, base, approved)
            if e:
                rows.append(("none", c, "bug" if approved else "correct", *e))
    for k in ("4", "1", "0.25"):
        fb = load(f"{prefix}_cost{k}_recheck")
        if fb is None:
            continue
        for c in FRAMED:
            r = load(f"{prefix}_cost{k}_{c}")
            if r is None:
                continue
            for approved in (True, False):
                e = excess(r, fb, approved)
                if e:
                    rows.append((f"K={k}", c, "bug" if approved else "correct", *e))
    return rows


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("prefixes", nargs="+")
    p.add_argument("--prefix-style", choices=["api", "open"], default="api")
    p.add_argument("--out", default=None, help="write a Markdown table")
    args = p.parse_args()
    lines = []
    for prefix in args.prefixes:
        name = os.path.basename(prefix)
        lines += [f"\n### {name}\n", "| framing | condition | claim | exploratory excess | 90% prediction interval | n |",
                  "| --- | --- | --- | --- | --- | --- |"]
        for fr, c, d, m, lo, hi, n in table(prefix, args.prefix_style):
            lines.append(f"| {fr} | {c} | {d} | {m:+.1f} | [{lo:+.1f}, {hi:+.1f}] | {n} |")
    text = "\n".join(lines)
    print(text)
    if args.out:
        with open(args.out, "w") as f:
            f.write("<!-- generated by confirm_predictions.py from the exploratory runs; excess switching over "
                    "re-check in percentage points -->\n" + text + "\n")
        print(f"\nsaved {args.out}")


if __name__ == "__main__":
    main()
