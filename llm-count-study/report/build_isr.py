def add_page_numbers(d):
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    for sec in d.sections:
        p = sec.footer.paragraphs[0] if sec.footer.paragraphs else sec.footer.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run()
        for typ, txt in (("begin", None), (None, " PAGE "), ("end", None)):
            if typ:
                e = OxmlElement("w:fldChar"); e.set(qn("w:fldCharType"), typ)
            else:
                e = OxmlElement("w:instrText"); e.set(qn("xml:space"), "preserve"); e.text = txt
            r._r.append(e)


def polish(path):
    from docx import Document
    from docx.shared import Pt, RGBColor, Inches
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    d = Document(path)
    for st in d.styles:
        if st.type != 1:
            continue
        if st.name in ("Normal", "Body Text", "First Paragraph", "Compact", "Block Text"):
            st.font.name = "Times New Roman"; st.font.size = Pt(12)
            if st.name in ("Body Text", "First Paragraph"):
                st.paragraph_format.line_spacing = 2.0; st.paragraph_format.space_after = Pt(0)
                st.paragraph_format.first_line_indent = Pt(24)
        if st.name.startswith("Heading") or st.name in ("Title", "Author"):
            st.font.name = "Times New Roman"; st.font.color.rgb = RGBColor(0, 0, 0)
            st.font.size = Pt(12 if st.name.startswith("Heading") else 14); st.font.bold = st.name != "Author"
            st.paragraph_format.space_before = Pt(12); st.paragraph_format.space_after = Pt(6)
        if st.name == "Heading 2":
            st.font.italic = True
        if st.name in ("Title", "Author"):
            st.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for p in d.paragraphs:  # keep captions, list items and the abstract readable
        if p.style.name in ("Body Text", "First Paragraph") and (p.text.startswith("Table") or p.text.startswith("Figure")):
            p.paragraph_format.line_spacing = 1.0; p.paragraph_format.first_line_indent = Pt(0)
    for t in d.tables:
        b = OxmlElement("w:tblBorders")
        for edge in ("top", "bottom", "insideH"):
            e = OxmlElement(f"w:{edge}"); e.set(qn("w:val"), "single"); e.set(qn("w:sz"), "4"); e.set(qn("w:color"), "808080"); b.append(e)
        t._tbl.tblPr.append(b)
        for ri, row in enumerate(t.rows):
            for c in row.cells:
                for p in c.paragraphs:
                    p.paragraph_format.space_before = Pt(1); p.paragraph_format.space_after = Pt(1)
                    p.paragraph_format.line_spacing = 1.0; p.paragraph_format.first_line_indent = Pt(0)
                    for r in p.runs:
                        r.font.size = Pt(8.5); r.font.name = "Times New Roman"; r.bold = True if ri == 0 else r.bold
    add_page_numbers(d)
    for sec in d.sections:
        sec.left_margin = sec.right_margin = sec.top_margin = sec.bottom_margin = Inches(1)
    d.save(path)


